  console.log(JSON.stringify({ ok: true, passed: ['native photo picker, crop and local persistence across restart', 'profile name, sidebar and conversation avatars, safe photo removal', 'Markdown links and native picker stay in Haven', 'relative document links, local images and GFM tables', 'light and dark screenshots', 'Needs you click and keyboard cycling preserve drafts'], data: root }, null, 2));
