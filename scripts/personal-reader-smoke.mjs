  assert.equal(settings.profileName, 'Alex Rivera'); assert.match(settings.profilePhoto, /^data:image\/png;base64,/);
  assert.equal(await app.evaluate(({ nativeImage }, data) => nativeImage.createFromDataURL(data).getSize().width, settings.profilePhoto), 256);
  await page.screenshot({ path: 'artifacts/profile-light.png', animations: 'disabled' });
  await page.getByRole('button', { name: 'Close dialog', exact: true }).click();
  await page.locator('.profile-button img').waitFor(); await page.locator('.user-avatar img').waitFor();
  await page.getByRole('link', { name: 'Read the document', exact: true }).click();
  await page.getByRole('dialog').waitFor();
  await page.getByRole('heading', { name: 'A little clarity', exact: true }).waitFor();
  assert.equal(await page.getByRole('dialog').locator('table').count(), 1);
  await page.getByLabel('Document contents', { exact: true }).waitFor();
  await page.getByRole('dialog').locator('.reader-image').scrollIntoViewIfNeeded();
  await page.getByRole('dialog').locator('img').waitFor();
  await page.waitForFunction(() => Number(document.querySelector('[aria-label="Reading progress"]').getAttribute('aria-valuenow')) > 0);
  await page.locator('.reader-viewport').evaluate(element => { element.scrollTop = 0; });
  assert.equal((await app.evaluate(() => globalThis.__externalCalls)).length, 0, 'Markdown must stay inside Haven');
  await page.screenshot({ path: 'artifacts/markdown-reader-light.png', animations: 'disabled' });
  await page.getByRole('link', { name: 'Next document', exact: true }).click();
  await page.getByRole('heading', { name: 'Next steps', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Back to previous document', exact: true }).click();
  await page.getByRole('heading', { name: 'A little clarity', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Copy', exact: true }).click();
  assert.equal(await app.evaluate(() => globalThis.__copiedText), content);
  await page.keyboard.press('Escape');
  await page.getByRole('dialog').waitFor({ state: 'hidden' });
  assert.equal(await page.getByRole('textbox', { name: 'Message', exact: true }).inputValue(), task.draft);
  await app.evaluate(() => { globalThis.__pickerFile = globalThis.__document; });
  await page.getByRole('button', { name: 'Files', exact: true }).click();
  await page.getByRole('heading', { name: 'A little clarity', exact: true }).waitFor();
  await page.evaluate(() => window.haven.invoke('settings', { theme: 'dark' }));
  await page.waitForFunction(() => document.documentElement.dataset.theme === 'dark');
  await page.screenshot({ path: 'artifacts/markdown-reader-dark.png', animations: 'disabled' });
