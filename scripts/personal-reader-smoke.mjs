import path from 'node:path';
import os from 'node:os';
import assert from 'node:assert/strict';
import { Store } from '../electron/core.mjs';

const root = fs.mkdtempSync(path.join(os.tmpdir(), 'haven-personal-reader-'));
const docs = path.join(root, 'notes'); fs.mkdirSync(docs);
const document = path.join(docs, 'A little clarity.md'), next = path.join(docs, 'Next.md'), photo = path.join(docs, 'portrait.png');
const content = '# A little clarity\n\nA focused place for your **next big idea**.\n\n## The plan\n\n- [x] Keep the work together\n- [ ] Make room to think\n\n| Step | Status |\n| --- | --- |\n| Read | Ready |\n| Decide | Yours |\n\n[Next document](./Next.md#next-steps)\n\n[Website](https://example.com)\n\n![A local illustration](./portrait.png)\n\n## Technical notes\n\n```js\nconst space = "Haven";\n```\n\n' + Array.from({ length: 12 }, (_, i) => `## Chapter ${i + 1}\n\nA quiet paragraph to test reading progress and navigation.\n\n`).join('');
fs.writeFileSync(document, content); fs.writeFileSync(next, '# Next document\n\n## Next steps\n\nYou stayed in Haven.\n');
const store = new Store(root), task = store.create({ name: 'Reading room', engine: 'claude', cwd: root });
store.add(task.id, 'user', 'Keep this draft and conversation safe.');
