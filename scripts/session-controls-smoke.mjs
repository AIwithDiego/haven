import { _electron as electron } from 'playwright';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import assert from 'node:assert/strict';
import { Store } from '../electron/core.mjs';
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'haven-controls-ui-'));
const store = new Store(root);
const first = store.create({ name: 'Feedback review', engine: 'claude', cwd: root });
store.add(first.id, 'user', 'Please review the task controls.'); store.add(first.id, 'assistant', 'Your conversation is saved here.');
const second = store.create({ name: 'Today’s focus', engine: 'claude', cwd: root });
store.state.activeId = first.id; store.save();
const app = await electron.launch({ ...(process.env.HAVEN_APP_PATH ? { executablePath: process.env.HAVEN_APP_PATH, args: [] } : { args: ['.'] }), cwd: process.cwd(), env: { ...process.env, HAVEN_DATA_DIR: root, HAVEN_TEST_MODE: '1' } });
const page = await app.firstWindow(); const errors = []; page.on('pageerror', e => errors.push(e.message));
const snapshot = () => page.evaluate(() => window.haven.invoke('state'));
const send = async text => { await page.getByRole('textbox', { name: 'Message', exact: true }).fill(text); await page.getByRole('button', { name: 'Send message', exact: true }).click(); };
try {
  await page.getByText('Your conversation is saved here.').waitFor();
  await send('/model'); await page.getByRole('heading', { name: 'Choose your model.' }).waitFor();
  await page.getByRole('combobox', { name: 'Available models', exact: true }).selectOption('sonnet'); await page.getByRole('button', { name: 'Use model', exact: true }).click();
  await page.waitForFunction(async id => (await window.haven.invoke('state')).sessions.find(s => s.id === id).model === 'sonnet', first.id);
  assert.equal((await snapshot()).sessions.find(s => s.id === first.id).messages.length, 2);
  await send('/status'); await page.getByRole('heading', { name: 'Task time', exact: true }).waitFor();
  await page.screenshot({ animations: 'disabled', path: 'artifacts/session-times-light.png' });
  await page.getByRole('button', { name: 'Pin task', exact: true }).click();
  await page.waitForFunction(async id => (await window.haven.invoke('state')).sessions.find(s => s.id === id).pinned, first.id);
  await page.getByRole('textbox', { name: 'Message', exact: true }).fill('/ex');
  await page.getByRole('option').filter({ hasText: '/exit' }).waitFor();
  await page.getByRole('textbox', { name: 'Message', exact: true }).press('Enter');
  assert.equal(await page.getByRole('textbox', { name: 'Message', exact: true }).inputValue(), '/exit ');
  await page.getByRole('textbox', { name: 'Message', exact: true }).press('Meta+Enter');
  await page.getByRole('button', { name: 'Reopen task', exact: true }).waitFor();
  assert.equal((await snapshot()).sessions.find(s => s.id === first.id).closed, true);
  assert.equal(await page.getByRole('textbox', { name: 'Message', exact: true }).count(), 0);
  await page.getByRole('button', { name: 'Reopen task', exact: true }).click();
  await send('/archive');
  await page.getByRole('button', { name: 'Restore task', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Archive', exact: true }).click();
  await page.screenshot({ animations: 'disabled', path: 'artifacts/archive-times-light.png' });
  await page.getByRole('button', { name: 'Delete Feedback review', exact: true }).click();
  await page.screenshot({ animations: 'disabled', path: 'artifacts/delete-task-light.png' });
  await page.getByRole('button', { name: 'Keep task', exact: true }).click();
  assert.ok((await snapshot()).sessions.find(s => s.id === first.id));
  await page.getByRole('button', { name: 'Delete Feedback review', exact: true }).click();
  await page.getByRole('button', { name: 'Delete permanently', exact: true }).click();
  await page.waitForFunction(async id => !(await window.haven.invoke('state')).sessions.some(s => s.id === id), first.id);
  await page.getByRole('heading', { name: 'Delete “Feedback review”?' }).waitFor({ state: 'hidden' });
  await page.getByRole('button', { name: 'Close dialog', exact: true }).click();
  await page.getByRole('textbox', { name: 'Message', exact: true }).fill('Keep this thought');
  await page.getByRole('button', { name: 'Commands, skills and protocols' }).click();
  await page.getByRole('textbox', { name: 'Search commands' }).fill('rename');
  await page.getByRole('option').filter({ hasText: '/rename' }).click();
  assert.equal(await page.getByRole('textbox', { name: 'Message', exact: true }).inputValue(), '/rename Keep this thought');
  await send('/clear');
  await page.waitForFunction(async id => (await window.haven.invoke('state')).activeId !== id, second.id);
  const current = await snapshot(); assert.equal(current.sessions.find(s => s.id === second.id).archived, true);
  await page.evaluate(() => window.haven.invoke('settings', { theme: 'dark' }));
  await page.waitForFunction(() => document.documentElement.dataset.theme === 'dark');
  await page.getByRole('textbox', { name: 'Message', exact: true }).fill('/');
  await page.getByRole('option').filter({ hasText: '/exit' }).waitFor();
  await page.screenshot({ animations: 'disabled', path: 'artifacts/slash-commands-dark.png' });
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ ok: true, tested: ['local model command without model turn', 'session timestamps', 'pin', 'slash keyboard insertion', 'exit and reopen', 'archive timestamps', 'cancel deletion', 'confirmed deletion', 'command picker preserves draft', 'fresh context'], data: root }, null, 2));
} catch (error) { await page.screenshot({ animations: 'disabled', path: 'artifacts/controls-failure.png' }); console.error(await page.locator('body').innerText()); throw error; } finally { await app.close(); }
